def _as_tuple(r):
    b = r.breakdown
    return (b.pace, b.consistency, b.momentum, b.effort, r.total, r.grade, r.grade_label,
            r.current_streak, r.best_streak)


def test_case_list_matches_expected():
    assert [c[0] for c in CASES] == list(EXPECTED)


@pytest.mark.parametrize("name,goal,check_ins,milestones,today", CASES, ids=[c[0] for c in CASES])
def test_legacy_goal_score_unchanged(name, goal, check_ins, milestones, today):
    assert goal.start_value is None and goal.frequency_type is None and goal.weekdays is None
    assert _as_tuple(score_goal(goal, check_ins, milestones, today)) == EXPECTED[name]


@pytest.mark.parametrize("name,goal,check_ins,milestones,today", CASES, ids=[c[0] for c in CASES])
def test_explicit_backend_defaults_unchanged(name, goal, check_ins, milestones, today):
    """What the backend will send for pre-customisation goals: start_value=0
    for numeric goals and frequency_type=per_week for habits. Must be identical."""
    kwargs = {}
    if goal.type == GoalType.NUMERIC:
        kwargs["start_value"] = 0.0
    if goal.type == GoalType.HABIT:
        kwargs["frequency_type"] = FrequencyType.PER_WEEK
    upgraded = replace(goal, **kwargs)
    assert _as_tuple(score_goal(upgraded, check_ins, milestones, today)) == EXPECTED[name]


def test_readme_worked_example_still_84():
    goal = Goal(
        type=GoalType.NUMERIC,
        status=GoalStatus.ACTIVE,
        start_date=date(2026, 9, 1),
        created_at=date(2026, 9, 1),
        target_value=80.0,
        current_value=50.0,
        frequency_per_week=3,
        deadline=date(2026, 11, 1),
    )
    check_ins = [
        CheckIn(logged_for=date(2026, 10, 2), effort_rating=4),
        CheckIn(logged_for=date(2026, 10, 3), effort_rating=3),
        CheckIn(logged_for=date(2026, 10, 10), effort_rating=5),
        CheckIn(logged_for=date(2026, 10, 13), effort_rating=4),
        CheckIn(logged_for=date(2026, 10, 14), effort_rating=5),
    ]
    for g in (goal, replace(goal, start_value=0.0)):
        r = score_goal(g, check_ins, [], date(2026, 10, 14))
        assert r.total == 84
        assert (r.grade, r.grade_label) == ("A", "Strong")
        assert r.breakdown.pace == pytest.approx(0.8866279069767442)
